// Render the captured demo drafts, not a replacement RFP. No runtime Markdown dependency.
import { readFileSync, writeFileSync } from 'node:fs';

const assets = new URL('../public/landing-assets/', import.meta.url);
const escape = value => value.replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
const inline = value => escape(value).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
  .replace(/\[(\d+)\]/g, '<button type="button" class="sw-rfp-citation" data-rfp-cite="$1" aria-label="Read RFP source $1">[$1]</button>');

function blocks(markdown) {
  const lines = markdown.trim().split('\n'), result = [];
  for (let i = 0; i < lines.length;) {
    if (!lines[i].trim()) { i++; continue; }
    if (lines[i].startsWith('|')) {
      const rows = [];
      while (i < lines.length && lines[i].startsWith('|')) {
        const cells = lines[i++].trim().slice(1, -1).split('|').map(value => value.trim());
        if (!cells.every(value => /^:?-+:?$/.test(value))) rows.push(cells);
      }
      const summary = rows[0][0] === 'Project';
      const renderRow = (cells, header) => `<tr>${cells.map((value, index) => `<${header ? 'th scope="col"' : summary && index === 0 ? 'th scope="row"' : 'td'}>${inline(value)}</${header || summary && index === 0 ? 'th' : 'td'}>`).join('')}</tr>`;
      result.push(`<table class="sw-rfp-table${summary ? ' sw-rfp-summary' : ''}">${summary ? '' : `<thead>${renderRow(rows.shift(), true)}</thead>`}<tbody>${rows.map(cells => renderRow(cells, false)).join('')}</tbody></table>`);
    } else if (/^(\d+\.|-) /.test(lines[i])) {
      const ordered = /^\d+\./.test(lines[i]), list = [];
      while (i < lines.length && /^(\d+\.|-) /.test(lines[i])) list.push(`<li style="--sw-item-delay:${list.length * 90}ms">${inline(lines[i++].replace(/^(\d+\.|-) /, '').trim())}</li>`);
      result.push(`<${ordered ? 'ol' : 'ul'}>${list.join('')}</${ordered ? 'ol' : 'ul'}>`);
    } else {
      const paragraph = [];
      while (i < lines.length && lines[i].trim() && !/^(\||\d+\. |\- )/.test(lines[i])) paragraph.push(lines[i++].trim());
      result.push(`<p>${inline(paragraph.join(' '))}</p>`);
    }
  }
  return result;
}

const drafts = Object.fromEntries(['architect', 'civil-stormwater', 'electrical', 'hydraulic'].map(key => {
  const markdown = readFileSync(new URL(`${key}-rfp.md`, assets), 'utf8');
  const [title, ...parts] = markdown.split(/^## /m);
  return [key, {
    title: title.replace(/^# /, '').trim(),
    sections: parts.map(part => {
      const end = part.indexOf('\n');
      return { title: part.slice(0, end).trim(), blocks: blocks(part.slice(end)) };
    }),
  }];
}));
writeFileSync(new URL('landing-rfp-data.js', assets), `// Generated by scripts/build-landing-rfp.mjs from the saved synthetic project drafts.\nexport const rfpDrafts = ${JSON.stringify(drafts, null, 2)};\n`);
