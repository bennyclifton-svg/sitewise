import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const frontend = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(frontend, '../Landing/design/colour-system');
const tokens = JSON.parse(await readFile(resolve(source, 'sitewise-colours.json'), 'utf8'));
const primitives = Object.fromEntries(Object.entries(tokens.primitives).map(([name, value]) => [name, value.hex]));
const themes = Object.fromEntries(Object.entries(tokens.themes).map(([mode, roles]) => [mode,
  Object.fromEntries(Object.entries(roles).map(([role, primitive]) => [role, primitives[primitive]])),
]));
const canvas = Object.fromEntries(Object.entries(themes).map(([mode, roles]) => [mode, roles.canvas]));
const header = '// Generated by scripts/sync-colour-tokens.mjs from the approved SiteWise colour specification.\n';
const exports = header + [
  ['SITEWISE_PRIMITIVES', primitives], ['SITEWISE_THEMES', themes],
  ['SITEWISE_DATA_SERIES', tokens.dataSeries], ['themeCanvasColours', canvas],
].map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)};`).join('\n\n') + '\n';
const boot = header + `/* Set the stored theme before first paint; storage key matches src/lib/theme.ts. */
(function () {
  var theme = 'dark';
  try {
    var stored = window.localStorage.getItem('clerk.colorTheme.v1');
    if (stored === 'light' || stored === 'dark') theme = stored;
  } catch { /* Blocked storage retains the default. */ }
  var root = document.documentElement;
  root.setAttribute('data-theme', theme);
  root.style.colorScheme = theme;
  var scheme = document.querySelector('meta[name="color-scheme"]');
  if (scheme) scheme.setAttribute('content', theme);
  var colour = document.querySelector('meta[name="theme-color"]');
  if (colour) colour.setAttribute('content', ${JSON.stringify(canvas)}[theme]);
})();
`;
// Keep the approved S silhouette; only its colour changes in browser chrome.
const mark = (await readFile(resolve(frontend, 'public/brand/sitewise-mark.png'))).toString('base64');
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
<style>rect{fill:${primitives['cyan-700']}}@media(prefers-color-scheme:dark){rect{fill:${primitives['cyan-300']}}}</style>
<defs><mask id="mark" mask-type="alpha"><image href="data:image/png;base64,${mark}" width="100" height="100"/></mask></defs>
<rect width="100" height="100" mask="url(#mark)"/>
</svg>\n`;
const outputs = new Map([
  ['public/style-guide/sitewise-colours.css', await readFile(resolve(source, 'sitewise-colours.css'), 'utf8')],
  ['public/style-guide/tokens.json', JSON.stringify(tokens, null, 2) + '\n'],
  ['public/style-guide/sitewise-colours.js', exports],
  ['src/lib/colour-tokens.ts', exports],
  ['public/style-guide/theme-boot.js', boot],
  ['public/brand/sitewise-favicon.svg', favicon],
]);
for (const [relative, content] of outputs) {
  const target = resolve(frontend, relative);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== content) throw new Error(`Colour export is stale: ${relative}`);
  } else {
    await writeFile(target, content, 'utf8');
  }
}
console.log(`SiteWise colour exports ${process.argv.includes('--check') ? 'verified' : 'synchronised'} (${outputs.size} files).`);
